#!/usr/bin/env bash

set -euo pipefail

project_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="${1:-$HOME/.config/env_vars/dev.env}"
env_file="${env_file/#\~/$HOME}"

if [[ ! -f "$project_dir/docker-compose.yml" ]]; then
  printf 'Could not find docker-compose.yml in %s\n' "$project_dir" >&2
  exit 1
fi

if [[ ! -r "$env_file" ]]; then
  printf 'Environment file is missing or unreadable: %s\n' "$env_file" >&2
  printf 'Usage: %s /absolute/path/to/dev.env\n' "$0" >&2
  exit 1
fi

config_dir="$HOME/.config/market-data-analysis"
helper_file="$config_dir/dev-compose.sh"
bashrc_file="$HOME/.bashrc"
mkdir -p "$config_dir"

printf -v quoted_project '%q' "$project_dir"
printf -v quoted_env '%q' "$env_file"

cat > "$helper_file" <<EOF
# Generated by scripts/install_dev_commands.sh; rerun it to update these paths.
_mda_project_dir=$quoted_project
_mda_env_file=$quoted_env

_mda_compose() {
  docker compose --project-directory "\$_mda_project_dir" \\
    --env-file "\$_mda_env_file" \\
    -f "\$_mda_project_dir/docker-compose.yml" "\$@"
}

dev_up() { _mda_compose up -d "\$@"; }
dev_down() { _mda_compose down "\$@"; }
dev_restart() { _mda_compose up -d --build --force-recreate "\$@"; }
dev_build() { _mda_compose build "\$@"; }
EOF

touch "$bashrc_file"
source_line='source "$HOME/.config/market-data-analysis/dev-compose.sh"'
if ! grep -Fqx "$source_line" "$bashrc_file"; then
  printf '\n# Market Data Analysis Docker Compose shortcuts\n%s\n' "$source_line" >> "$bashrc_file"
fi

printf 'Installed dev_up, dev_down, and dev_restart in %s\n' "$helper_file"
printf 'Run: source %s\n' "$bashrc_file"
